// Helper to normalize Ukrainian strings (strip stress and apostrophe variants)
export function normalizeUkrainianText(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’ʼ`]/g, "'")
    .replace(/[«»"“”!?.,;:—()-]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

export interface AnswerValidationResult {
  isCorrect: boolean;
  isExactWithStress: boolean;
  normalizedUser: string;
  normalizedExpected: string;
  feedbackMessage: string;
}

/**
 * Validates a learner's Ukrainian answer according to Master Prompt Part 6.2:
 * - Ignores capitalization differences
 * - Ignores optional stress marks (so learners are not penalized for omitting acute accents)
 * - Normalizes apostrophe variants (' / ’ / ʼ)
 * - Clearly explains genuine spelling or grammatical case/ending errors
 */
export function validateUkrainianAnswer(
  userAnswer: string,
  expectedUk: string,
  acceptedAlternatives: string[] = []
): AnswerValidationResult {
  const rawUser = userAnswer.trim();
  const normUser = normalizeUkrainianText(rawUser);
  const normExpected = normalizeUkrainianText(expectedUk);
  const normAlts = acceptedAlternatives.map(normalizeUkrainianText);

  const isCorrect =
    normUser.length > 0 &&
    (normUser === normExpected || normAlts.includes(normUser));

  const isExactWithStress =
    rawUser.toLowerCase() === expectedUk.toLowerCase();

  let feedbackMessage = '';
  if (isCorrect) {
    feedbackMessage = `✅ Correct! Stressed form: «${expectedUk}».`;
  } else if (!normUser) {
    feedbackMessage = `Type an answer first. Expected form: «${expectedUk}».`;
  } else {
    // Check if only the last 1-2 letters differ (likely a grammatical case/gender ending difference)
    const stemLen = Math.min(normUser.length, normExpected.length) - 2;
    if (
      stemLen >= 3 &&
      normUser.slice(0, stemLen) === normExpected.slice(0, stemLen)
    ) {
      feedbackMessage = `⚠️ Close stem, but check the grammatical ending: you wrote «${rawUser}», whereas the required form here is «${expectedUk}».`;
    } else {
      feedbackMessage = `❌ Not quite: you wrote «${rawUser}». The correct Ukrainian form is «${expectedUk}».`;
    }
  }

  return {
    isCorrect,
    isExactWithStress,
    normalizedUser: normUser,
    normalizedExpected: normExpected,
    feedbackMessage,
  };
}

/**
 * Retrieves all vocabulary items from FREQ_6000_DB belonging to a given category ID.
 */
export function getCategoryVocabItems(categoryId: string): VocabItem[] {
  const cat = EVERYDAY_CATEGORIES.find((c) => c.id === categoryId);
  if (!cat) return FREQ_6000_DB.slice(0, 25);

  const kwSet = new Set(cat.keywords.map(normalizeUkrainianText));
  const matched: VocabItem[] = [];
  const seenRanks = new Set<number>();

  for (const item of FREQ_6000_DB) {
    const cleanRu = normalizeUkrainianText(item.ru);
    const enLower = item.en.toLowerCase();
    let isMatch = kwSet.has(cleanRu);

    if (!isMatch) {
      for (const kw of kwSet) {
        if (kw.length >= 4 && cleanRu.startsWith(kw)) {
          isMatch = true;
          break;
        }
      }
    }

    // Category-specific semantic enrichment so every category has a rich set of words
    if (!isMatch) {
      if (categoryId === 'greetings' && (enLower.includes('hello') || enLower.includes('morning') || enLower.includes('thank') || enLower.includes('please') || enLower.includes('excuse'))) isMatch = true;
      if (categoryId === 'family' && (enLower.includes('mother') || enLower.includes('father') || enLower.includes('sister') || enLower.includes('brother') || enLower.includes('family') || enLower.includes('friend'))) isMatch = true;
      if (categoryId === 'food' && (enLower.includes('bread') || enLower.includes('milk') || enLower.includes('meat') || enLower.includes('fruit') || enLower.includes('vegetable') || enLower.includes('soup') || enLower.includes('cheese'))) isMatch = true;
      if (categoryId === 'adjectives' && item.pos.startsWith('ADJ')) isMatch = true;
      if (categoryId === 'adverbs' && item.pos.startsWith('ADV')) isMatch = true;
      if (categoryId === 'prepositions' && item.pos.startsWith('PREP')) isMatch = true;
      if (categoryId === 'verbs' && item.pos.startsWith('VERB') && matched.length < 35) isMatch = true;
    }

    if (isMatch && !seenRanks.has(item.rank)) {
      seenRanks.add(item.rank);
      matched.push(item);
    }
  }

  return matched;
}

